#!/usr/bin/env node
// Builds scripts/even-steven.bundle.mjs: one self-contained file (viem inlined, no node_modules needed at run time).
// Not minified, so it stays reviewable. Deterministic: the unit tests rebuild it in memory and fail if the
// committed bundle is stale.   node scripts/build.mjs [--check]
import { build } from 'esbuild'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
export const ENTRY = path.join(here, 'even-steven.mjs')
export const OUT = path.join(here, 'even-steven.bundle.mjs')

export async function bundle() {
  const r = await build({
    entryPoints: [ENTRY], bundle: true, write: false, platform: 'node', format: 'esm', target: 'node20',
    minify: false, legalComments: 'none', treeShaking: true, logLevel: 'silent',
    banner: { js: "// GENERATED by scripts/build.mjs from scripts/even-steven.mjs with viem inlined. Do not edit.\nimport { createRequire as __cr } from 'node:module'\nconst require = __cr(import.meta.url)" },
    absWorkingDir: path.resolve(here, '..'),
  })
  return r.outputFiles[0].text
}
if (import.meta.url === `file://${process.argv[1]}`) {
  const text = await bundle()
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : ''
    if (cur !== text) { console.error('even-steven.bundle.mjs is stale: run node scripts/build.mjs'); process.exit(1) }
    console.log('bundle is up to date'); process.exit(0)
  }
  fs.writeFileSync(OUT, text, { mode: 0o755 })
  console.log(`wrote ${path.relative(process.cwd(), OUT)} (${(text.length / 1024).toFixed(0)} KB)`)
}
