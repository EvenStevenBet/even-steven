#!/usr/bin/env node
// Builds scripts/even-steven.bundle.mjs for the OpenClaw skill from the Bankr skill's source, with the optional attribution
// setting compiled out of this bundle only. The Bankr skill and its bundle are untouched. The replacement is exact and
// asserted: if the source line changes, this build fails instead of silently shipping the setting.
//   node scripts/build-openclaw.mjs [--check]
import { build } from 'esbuild'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const SRC_DIR = path.resolve(here, '../../../bankr/even-steven/scripts')
export const OUT = path.join(here, 'even-steven.bundle.mjs')
const NAME = 'ES_' + 'REF'                                  // spelled in two pieces so this file itself carries no such token
const READ = `env.${NAME} || undefined`

const stripRef = {
  name: 'strip-attribution-setting',
  setup(b) {
    b.onLoad({ filter: /even-steven\.mjs$/ }, (args) => {
      let t = fs.readFileSync(args.path, 'utf8')
      if (t.split(READ).length !== 2) throw new Error('expected exactly one read of the attribution setting in the Bankr source')
      t = t.replace(READ, 'undefined')
      t = t.split(NAME).join('(removed)')                    // header comment and any other mention
      return { contents: t, loader: 'js', resolveDir: path.dirname(args.path) }
    })
  },
}

export async function bundle() {
  const r = await build({
    entryPoints: [path.join(SRC_DIR, 'even-steven.mjs')], bundle: true, write: false, platform: 'node', format: 'esm', target: 'node20',
    minify: false, legalComments: 'none', treeShaking: true, logLevel: 'silent', plugins: [stripRef],
    absWorkingDir: path.resolve(SRC_DIR, '..'), nodePaths: [path.resolve(here, '../node_modules')],
    banner: { js: "// GENERATED by scripts/build-openclaw.mjs from the Bankr skill source with viem inlined. Do not edit.\nimport { createRequire as __cr } from 'node:module'\nconst require = __cr(import.meta.url)" },
  })
  const text = r.outputFiles[0].text
  if (text.includes(NAME)) throw new Error('the attribution setting is still present in the bundle')
  return text
}
if (import.meta.url === `file://${fs.realpathSync(process.argv[1])}`) {
  const text = await bundle()
  if (process.argv.includes('--check')) {
    if ((fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '') !== text) { console.error('bundle is stale: run npm run build'); process.exit(1) }
    console.log('bundle is up to date'); process.exit(0)
  }
  fs.writeFileSync(OUT, text, { mode: 0o755 }); console.log(`wrote ${path.relative(process.cwd(), OUT)} (${(text.length / 1024).toFixed(0)} KB)`)
}
